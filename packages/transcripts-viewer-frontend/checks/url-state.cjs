const {chromium}=require('playwright')
const assert=require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH})
 const base=process.env.VIEWER_URL||'http://localhost:5173'
 const context=await browser.newContext({viewport:{width:1440,height:1000}})
 const page=await context.newPage()
 page.setDefaultTimeout(15000)
 page.on('pageerror',e=>console.log('PAGEERROR',String(e)))
 async function reloadAndCopy(check){
  const url=page.url();console.log('Restoring',new URL(url).hash.slice(0,100));await page.reload();await check(page)
  const fresh=await browser.newContext({viewport:{width:1440,height:1000}}),tab=await fresh.newPage()
  try{await tab.goto(url);await check(tab)}finally{await fresh.close()}
 }
 try{
  await page.goto(`${base}/#run/20261113-034702-wild-recipe`)
  await page.getByRole('button',{name:'Collapse Graphs',exact:true}).click()
  await reloadAndCopy(p=>p.getByRole('button',{name:'Expand Graphs',exact:true}).waitFor())
  await page.getByRole('button',{name:'Expand Graphs',exact:true}).click()
  assert.ok(!new URLSearchParams(new URL(page.url()).hash.split('?')[1]).has('panel:/graphs'))
  await page.getByRole('button',{name:'Collapse Window 0',exact:true}).click()
  await reloadAndCopy(p=>p.getByRole('button',{name:'Expand Window 0',exact:true}).waitFor())
  await page.getByRole('button',{name:'Log (1 + score)',exact:true}).first().click()
  const knob=page.locator('.run-graphs .x-slider [data-knob="lo"]')
  const box=await knob.boundingBox(),track=await page.locator('.run-graphs .x-slider .track').boundingBox()
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down()
  await page.mouse.move(track.x+track.width*.2,box.y+box.height/2);await page.mouse.up()
  await reloadAndCopy(async p=>{
   await p.locator('.run-graphs button[aria-pressed="true"]').waitFor()
   await p.waitForFunction(()=>Number(document.querySelector('.run-graphs .x-slider .selected')?.getAttribute('x1'))>0)
  })
  await page.goto(`${base}/#run/20261113-034702-wild-recipe`)
  await page.locator('.run-graphs .chart-point').first().click()
  const header=await page.locator('.p-dialog-title').innerText()
  await reloadAndCopy(async p=>{
   await p.getByText(header,{exact:true}).waitFor()
   await p.locator('.p-dialog .message-blocks [data-block]').first().waitFor()
  })
  await page.getByRole('button',{name:'Next U turn',exact:true}).click()
  const nextHeader=await page.locator('.p-dialog-title').innerText()
  assert.notEqual(nextHeader,header)
  await reloadAndCopy(p=>p.getByText(nextHeader,{exact:true}).waitFor())
  await page.locator('.p-dialog .block-navigation button').last().click()
  const block=await page.locator('.p-dialog .block-navigation [aria-current=true]').getAttribute('aria-label')
  await reloadAndCopy(p=>p.getByRole('button',{name:block,exact:true}).and(p.locator('[aria-current=true]')).waitFor())
  await page.getByRole('button',{name:'Close',exact:true}).click()
  assert.ok(!new URLSearchParams(new URL(page.url()).hash.split('?')[1]).has('modal'))
  await page.locator('.t-sample .transcript-button').first().click()
  if(await page.locator('.transcript-files').isVisible())await page.locator('.transcript-files button').first().click()
  const tHeader=await page.locator('.p-dialog-title').innerText()
  await reloadAndCopy(p=>p.getByText(tHeader,{exact:true}).waitFor())
  await page.getByRole('button',{name:'Close',exact:true}).click()
  await page.locator('.pass-blocks button').first().click()
  await reloadAndCopy(async p=>{
   await p.getByText('Test results',{exact:true}).waitFor()
   await p.locator('.json-content .is-highlight').first().waitFor()
  })
  await page.getByRole('button',{name:'Close',exact:true}).click()
  await page.getByRole('button',{name:'Open files',exact:true}).first().click()
  await reloadAndCopy(p=>p.locator('.files-viewer').waitFor())
  await page.getByRole('button',{name:'Close',exact:true}).click()
  await page.evaluate(async()=>{
   const {openFiles}=await import('/src/composables/filePreview.js')
   openFiles({name:'Fixture files',files:['question.txt','solutions.json'].map(name=>({name,path:name,source:name,url:`/api/runs/20261113-034702-wild-recipe/problem/${name}`}))})
  })
  await page.locator('.files-viewer .file-tree button').last().click()
  const selectedFile=await page.locator('.files-viewer .file-tree [aria-current=true]').innerText()
  await reloadAndCopy(p=>p.locator('.files-viewer .file-tree [aria-current=true]').filter({hasText:selectedFile}).waitFor())
  await page.getByRole('button',{name:'Close',exact:true}).click()
  await page.getByRole('link',{name:'question.txt',exact:true}).click()
  await reloadAndCopy(p=>p.getByText('question.txt',{exact:true}).and(p.locator('.p-dialog-title')).waitFor())
  await page.getByRole('button',{name:'Close',exact:true}).click()
  await page.goto(`${base}/#dashboard`)
  await page.getByRole('columnheader',{name:'Problem',exact:true}).click()
  await reloadAndCopy(p=>p.locator('th[aria-sort="descending"]').filter({hasText:'Problem'}).waitFor())
  console.log('U turn/block, T, test target, files selection, plain file modals and dashboard sort restore after reload/fresh tab.')
  console.log('Chart log and x range restore after reload/fresh tab. No dashboard charts.');
  console.log('Panels restore after reload/fresh tab; defaults omitted. Dashboard has no panels.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
