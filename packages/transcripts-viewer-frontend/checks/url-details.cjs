const {chromium}=require('playwright'),assert=require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH})
 const base=process.env.VIEWER_URL||'http://localhost:5173',page=await browser.newPage({viewport:{width:1440,height:1000}})
 page.setDefaultTimeout(15000)
 const errors=[];page.on('pageerror',e=>errors.push(String(e)))
 const run=`${base}/#run/20261113-034702-wild-recipe`
 async function copy(check){
  const url=page.url();await page.reload();await check(page)
  const context=await browser.newContext({viewport:{width:1440,height:1000}}),tab=await context.newPage()
  try{await tab.goto(url);await check(tab)}finally{await context.close()}
 }
 try{
  await page.goto(run)
  await page.getByRole('link',{name:'input_output.json',exact:true}).click()
  await page.locator('.p-dialog .vjs-carets').first().click()
  await copy(p=>p.locator('.p-dialog .vjs-carets-close').first().waitFor())
  await page.getByRole('button',{name:'Close',exact:true}).click()
  await page.locator('.turn-block [aria-label^="Metadata for"]').first().click()
  await page.waitForFunction(()=>[...new URLSearchParams(location.hash.split('?')[1]).keys()].some(k=>k.startsWith('metadata:')))
  await copy(p=>p.locator('.p-popover').filter({hasText:'Metadata for'}).waitFor())
  await page.keyboard.press('Escape')
  await page.mouse.move(1400,950)
  console.log('JSON expansion and pinned metadata restore after reload/fresh tab')
  await page.goto(run)
  await page.locator('.run-graphs .chart-point').first().click()
  const role=page.locator('.p-dialog .role-legend label').filter({hasText:'user'}).getByRole('checkbox')
  await role.uncheck()
  await copy(async p=>{await p.locator('.p-dialog .role-legend').waitFor();assert.equal(await p.locator('.p-dialog .role-legend label').filter({hasText:'user'}).getByRole('checkbox').isChecked(),false)})
  await page.getByRole('button',{name:'Close',exact:true}).click()
  await page.getByRole('combobox',{name:'Problem',exact:true}).click()
  await page.getByPlaceholder('Search Problem',{exact:true}).fill('1958')
  await page.waitForFunction(()=>new URLSearchParams(location.hash.split('?')[1]).get('select::Problem:open')==='true')
  await copy(async p=>{await p.getByPlaceholder('Search Problem',{exact:true}).waitFor();assert.equal(await p.getByPlaceholder('Search Problem',{exact:true}).inputValue(),'1958')})
  console.log('Transcript role filters and open/searching selector restore after reload/fresh tab')
  await page.goto(run)
  await page.locator('.run-transcripts .fork-chart').first().waitFor()
  await page.locator('.run-transcripts > .p-panel-content-container').evaluate(e=>{e.scrollTop=300})
  await page.waitForFunction(()=>new URLSearchParams(location.hash.split('?')[1]).has('scroll:transcripts'))
  await copy(async p=>{await p.waitForFunction(()=>Math.abs((document.querySelector('.run-transcripts > .p-panel-content-container')?.scrollTop??0)-300)<3)})
  console.log('Drilldown scroll position restores after reload/fresh tab')
  assert.deepEqual(errors,[])
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
